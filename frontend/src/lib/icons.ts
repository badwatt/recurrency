export function getIcon(name: string | null | undefined): LucideIcon {
  if (!name) return Tag;
  const pascal = name
    .split("-")
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join("");
  return icons[pascal] || Tag;
}